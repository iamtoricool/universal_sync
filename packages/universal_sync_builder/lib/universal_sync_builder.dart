/// Creates the `universal_sync` builder configured by `build.yaml`.
Builder syncBuilder(BuilderOptions options) => const SyncBuilder();

/// Generates typed `SyncEntity` descriptors, a registry and engine extensions
/// for `@SyncDatabase` classes and their `@Syncable` tables.
final class SyncBuilder implements Builder {
  const SyncBuilder();

  @override
  Map<String, List<String>> get buildExtensions => const {
    '.dart': ['.sync.dart'],
  };

  @override
  FutureOr<void> build(BuildStep buildStep) async {
    final library = await buildStep.resolver.libraryFor(buildStep.inputId);
    final databases = library.classes.where(_hasSyncDatabase).toList();
    if (databases.isEmpty) return;

    final imports = <String>{};
    final bodies = <String>[];
    for (final database in databases) {
      final section = _DatabaseGenerator(library, database).generate();
      if (section == null) continue;
      imports.addAll(section.imports);
      bodies.add(section.body);
    }
    if (bodies.isEmpty) return;

    final source =
        '$_header\n'
        '${imports.map((import) => "import '$import';").join('\n')}\n\n'
        '$generatedPreamble\n'
        '${bodies.join('\n\n')}';
    final formatter = DartFormatter(
      languageVersion: DartFormatter.latestLanguageVersion,
    );
    final formatted = formatter.format(source);
    await buildStep.writeAsString(
      buildStep.inputId.changeExtension('.sync.dart'),
      formatted,
    );
  }
}

const _header = '''
// GENERATED CODE - DO NOT MODIFY BY HAND.
// Generated by package:universal_sync_builder.
// ignore_for_file: type=lint
''';

const generatedPreamble = '''
const _universalSyncWireSerializer =
    ValueSerializer.defaults(serializeDateTimeValuesAsString: true);
''';

final class _Section {
  const _Section(this.imports, this.body);

  final Set<String> imports;
  final String body;
}

final class _DatabaseGenerator {
  _DatabaseGenerator(this.library, this.database);

  final LibraryElement library;
  final ClassElement database;

  _Section? generate() {
    final prefix = _stringField(database, 'SyncDatabase', 'prefix') ?? '';
    final entities = <_Entity>[];
    for (final table in _tablesOf(database)) {
      final annotation = _annotation(table, 'Syncable', 'universal_sync');
      if (annotation == null) continue;
      entities.add(_Entity.fromTable(table, annotation, prefix));
    }
    if (entities.isEmpty) return null;

    final imports = <String>{
      'package:drift/drift.dart',
      'package:universal_sync/universal_sync.dart',
      database.library.uri.toString(),
      for (final entity in entities) entity.table.library.uri.toString(),
    };

    final buffer = StringBuffer();
    for (final entity in entities) {
      buffer.writeln(entity.generateAdapter(database.name!));
      buffer.writeln();
    }

    buffer.writeln(_generateRegistry(prefix, entities));
    buffer.writeln();
    buffer.writeln(_generateEngineExtension(prefix, entities));
    buffer.writeln();
    buffer.writeln(_generateOpen(prefix));
    return _Section(imports, buffer.toString());
  }

  String _generateRegistry(String prefix, List<_Entity> entities) {
    final name = '${database.name}${_pascal(prefix)}Sync';
    final entries = entities.map((e) => '${e.functionName}(this)').join(',\n    ');
    return '''
extension $name on ${database.name} {
  List<SyncEntityBase> get syncEntities => <SyncEntityBase>[
    $entries,
  ];
}''';
  }

  String _generateEngineExtension(String prefix, List<_Entity> entities) {
    final name = '${database.name}${_pascal(prefix)}SyncEngine';
    final getters = entities
        .map(
          (e) =>
              '  SyncTable<${e.table.name}, ${e.rowClass}, ${e.keyType}> '
              'get ${e.getterName} => table(${e.functionName}(db));',
        )
        .join('\n');
    return '''
extension $name on UniversalSync<${database.name}> {
$getters
}''';
  }

  String _generateOpen(String prefix) {
    final name = 'open${_pascal(prefix)}Sync';
    return '''
Future<UniversalSync<${database.name}>> $name(
  ${database.name} database, {
  required SyncTransport transport,
  SyncSession session = const AnonymousSession(),
  SyncOptions options = const SyncOptions(),
  SyncBootstrap bootstrap = const SkipBootstrap(),
}) {
  return UniversalSync.open<${database.name}>(
    database: database,
    entities: database.syncEntities,
    transport: transport,
    session: session,
    options: options,
    bootstrap: bootstrap,
  );
}''';
  }
}

final class _Entity {
  const _Entity({
    required this.table,
    required this.key,
    required this.keyType,
    required this.updatedAt,
    required this.owner,
    required this.serverManagedColumns,
    required this.rowClass,
    required this.companionClass,
    required this.getterName,
    required this.functionName,
    required this.columns,
  });

  factory _Entity.fromTable(
    ClassElement table,
    ElementAnnotation annotation,
    String prefix,
  ) {
    final constant = annotation.computeConstantValue();
    final tableName = table.name!;
    final rowClass = _stringFieldFrom(constant, 'dataClassName') ?? _dataClassName(tableName);
    final companionClass = _stringFieldFrom(constant, 'companionName') ?? '${tableName}Companion';

    final getters = <String, GetterElement>{
      for (final getter in table.getters)
        if (getter.name != null && !getter.isStatic) getter.name!: getter,
    };
    final columns = <_Column>[];
    for (final getter in getters.values) {
      if (!_isDriftColumn(getter.returnType)) continue;
      final columnType = _rowTypeOf(getter.returnType);
      if (columnType == null) {
        throw _SyncableError(
          tableName,
          'column "${getter.name}" uses an unsupported column type '
          '(${getter.returnType.getDisplayString()}). universal_sync v1 '
          'supports TextColumn, IntColumn, BoolColumn, DateTimeColumn and '
          'RealColumn.',
        );
      }
      if (columnType == 'Uint8List') {
        throw _SyncableError(
          tableName,
          'column "${getter.name}" is a blob. Blob columns are not supported '
          'by the generator yet; use a text column or a hand-written '
          'SyncEntity.',
        );
      }
      columns.add(_Column(dartName: getter.name!, type: columnType));
    }
    if (columns.isEmpty) {
      throw _SyncableError(tableName, 'no columns were discovered.');
    }

    final keyName = constant?.getField('key')?.toSymbolValue();
    if (keyName == null) {
      throw _SyncableError(tableName, '@Syncable(key: #column) is required.');
    }
    final keyColumn = _firstOrNull(columns.where((c) => c.dartName == keyName));
    if (keyColumn == null) {
      throw _SyncableError(
        tableName,
        'key "#$keyName" does not name a column of $tableName.',
      );
    }
    if (!const {'String', 'int', 'double', 'bool'}.contains(keyColumn.type)) {
      throw _SyncableError(
        tableName,
        'key "#$keyName" has unsupported type ${keyColumn.type}. v1 supports '
        'String, int, double and bool primary keys.',
      );
    }

    final updatedAtName = constant?.getField('updatedAt')?.toSymbolValue();
    _Column? updatedAt;
    if (updatedAtName != null) {
      updatedAt = _firstOrNull(
        columns.where((c) => c.dartName == updatedAtName),
      );
      if (updatedAt == null || updatedAt.type != 'DateTime') {
        throw _SyncableError(
          tableName,
          'updatedAt "#$updatedAtName" must name a DateTime column.',
        );
      }
    }

    final ownerName = constant?.getField('owner')?.toSymbolValue();
    _Column? owner;
    if (ownerName != null) {
      owner = _firstOrNull(columns.where((c) => c.dartName == ownerName));
      if (owner == null || owner.type != 'String') {
        throw _SyncableError(
          tableName,
          'owner "#$ownerName" must name a String column.',
        );
      }
    }

    final serverManaged = <String>[
      for (final symbol in constant?.getField('serverManagedColumns')?.toListValue() ?? const <DartObject>[])
        ?symbol.toSymbolValue(),
    ];
    for (final name in serverManaged) {
      if (!columns.any((c) => c.dartName == name)) {
        throw _SyncableError(
          tableName,
          'serverManagedColumns contains "#$name", which is not a column.',
        );
      }
    }

    final prefixPart = prefix.isEmpty ? '' : '${_pascal(prefix)}${_pascal(tableName)}';
    return _Entity(
      table: table,
      key: keyColumn,
      keyType: keyColumn.type,
      updatedAt: updatedAt,
      owner: owner,
      serverManagedColumns: serverManaged,
      rowClass: rowClass,
      companionClass: companionClass,
      getterName: _camelCase(tableName),
      functionName: prefixPart.isEmpty ? '${_camelCase(tableName)}SyncEntity' : '${prefixPart}SyncEntity',
      columns: columns,
    );
  }

  final ClassElement table;
  final _Column key;
  final String keyType;
  final _Column? updatedAt;
  final _Column? owner;
  final List<String> serverManagedColumns;
  final String rowClass;
  final String companionClass;
  final String getterName;
  final String functionName;
  final List<_Column> columns;

  String generateAdapter(String databaseType) {
    final t = 'db.$getterName';
    final b = StringBuffer();

    b.writeln(
      'SyncEntity<${table.name}, $rowClass, $keyType> '
      '$functionName($databaseType db) {',
    );
    b.writeln('  final wireToDart = <String, String>{');
    for (final column in columns) {
      b.writeln("    $t.${column.dartName}.name: '${column.dartName}',");
    }
    b.writeln('  };');
    b.writeln('  final dartToWire = <String, String>{');
    for (final column in columns) {
      b.writeln("    '${column.dartName}': $t.${column.dartName}.name,");
    }
    b.writeln('  };');
    b.writeln();
    b.writeln('  return SyncEntity<${table.name}, $rowClass, $keyType>(');
    b.writeln('    table: $t,');
    b.writeln('    keyColumns: [$t.${key.dartName}.name],');
    b.writeln('    keyOf: (row) => row.${key.dartName},');
    b.writeln(
      '    whereKey: (table, key) => table.${key.dartName}.equals(key),',
    );
    b.writeln('    encode: (row) => <String, Object?>{');
    b.writeln('      for (final entry in row');
    b.writeln('          .toJson(serializer: _universalSyncWireSerializer)');
    b.writeln('          .entries)');
    b.writeln('        dartToWire[entry.key] ?? entry.key: entry.value,');
    b.writeln('    },');
    b.writeln('    decode: (json) => $rowClass.fromJson(');
    b.writeln('      <String, dynamic>{');
    b.writeln('        for (final entry in json.entries)');
    b.writeln('          wireToDart[entry.key] ?? entry.key: entry.value,');
    b.writeln('      },');
    b.writeln('      serializer: _universalSyncWireSerializer,');
    b.writeln('    ),');
    b.writeln('    keyParts: (key) => <Object?>[key],');
    b.writeln('    keyFromParts: (parts) => parts.first as $keyType,');
    b.writeln(
      '    keyPartsFromRow: (json) => '
      '<Object?>[json[$t.${key.dartName}.name]],',
    );
    if (updatedAt case final updatedAt?) {
      b.writeln('    updatedAtOf: (row) => row.${updatedAt.dartName},');
      b.writeln('    updatedAtColumn: $t.${updatedAt.dartName}.name,');
      b.writeln(
        '    stampUpdatedAt: (companion, now) => '
        '(companion as $companionClass)'
        '.copyWith(${updatedAt.dartName}: Value(now)),',
      );
    }
    if (owner case final owner?) {
      b.writeln('    ownerOf: (row) => row.${owner.dartName},');
      b.writeln('    ownerColumn: $t.${owner.dartName}.name,');
      b.writeln(
        '    stampOwner: (companion, owner) => '
        '(companion as $companionClass)'
        '.copyWith(${owner.dartName}: Value(owner)),',
      );
    }
    if (serverManagedColumns.isNotEmpty) {
      final columns = serverManagedColumns.map((name) => '$t.$name.name').join(', ');
      b.writeln('    serverManagedColumns: {$columns},');
    }
    b.writeln(
      '    expectedColumns: '
      '[for (final column in $t.\$columns) column.name],',
    );
    b.writeln('  );');
    b.writeln('}');
    return b.toString();
  }
}

final class _Column {
  const _Column({required this.dartName, required this.type});

  final String dartName;
  final String type;
}

final class _SyncableError implements Exception {
  _SyncableError(this.table, this.message);

  final String table;
  final String message;

  @override
  String toString() => 'universal_sync_builder: $table: $message';
}

// ── Analyzer helpers ────────────────────────────────────────────────────────

bool _hasSyncDatabase(ClassElement element) => _annotation(element, 'SyncDatabase', 'universal_sync') != null;

ElementAnnotation? _annotation(
  Element element,
  String name,
  String libraryHint,
) {
  for (final annotation in element.metadata.annotations) {
    final type = _annotationType(annotation);
    if (type == null) continue;
    if (type.displayName != name) continue;
    final uri = type.library?.uri.toString() ?? '';
    if (uri.contains(libraryHint)) return annotation;
  }
  return null;
}

/// `@Foo()` is represented by the constructor element `Foo.new`; return `Foo`.
///
/// Falls back to the constant's type when the resolver exposes annotations
/// without their constructor element (some build_test resolvers do).
Element? _annotationType(ElementAnnotation annotation) {
  final constantType = annotation.computeConstantValue()?.type?.element;
  if (constantType != null) return constantType;
  final element = annotation.element;
  if (element is ConstructorElement) return element.enclosingElement;
  return element;
}

String? _stringField(
  ClassElement element,
  String annotationName,
  String field,
) {
  final annotation = _annotation(element, annotationName, 'universal_sync');
  return _stringFieldFrom(annotation?.computeConstantValue(), field);
}

String? _stringFieldFrom(DartObject? constant, String field) => constant?.getField(field)?.toStringValue();

List<ClassElement> _tablesOf(ClassElement database) {
  for (final annotation in database.metadata.annotations) {
    final type = _annotationType(annotation);
    if (type == null) continue;
    if (type.displayName != 'DriftDatabase') continue;
    final uri = type.library?.uri.toString() ?? '';
    if (!uri.startsWith('package:drift/')) continue;

    final constant = annotation.computeConstantValue();
    final tables = constant?.getField('tables')?.toListValue() ?? const [];
    return [
      for (final table in tables)
        if (table.toTypeValue()?.element case final ClassElement element) element,
    ];
  }
  return const [];
}

bool _isDriftColumn(DartType type) {
  InterfaceType? current = type is InterfaceType ? type : null;
  while (current != null) {
    final element = current.element;
    final uri = element.library.uri.toString();
    if (element.displayName == 'Column' && uri.startsWith('package:drift/')) {
      return true;
    }
    current = element.supertype;
  }
  return false;
}

String? _rowTypeOf(DartType type) {
  if (type is! InterfaceType) return null;
  final element = type.element;
  final uri = element.library.uri.toString();
  if (!uri.startsWith('package:drift/')) return null;

  // TextColumn/IntColumn/... are typedefs for Column<T>; custom converters
  // are GeneratedColumnWithTypeConverter<D, S>, where D is the row type.
  if (element.displayName != 'Column' && element.displayName != 'GeneratedColumnWithTypeConverter') {
    return null;
  }
  if (type.typeArguments.isEmpty) return null;
  return type.typeArguments.first.getDisplayString();
}

String _dataClassName(String tableName) {
  if (tableName.endsWith('s')) {
    if (tableName.endsWith('ss') || tableName.endsWith('us') || tableName.endsWith('sses')) {
      return '${tableName}Data';
    }
    if (tableName.endsWith('ies')) {
      return '${tableName.substring(0, tableName.length - 3)}y';
    }
    return tableName.substring(0, tableName.length - 1);
  }
  return '${tableName}Data';
}

String _camelCase(String value) => value.isEmpty ? value : value[0].toLowerCase() + value.substring(1);

String _pascal(String value) => value.isEmpty ? value : value[0].toUpperCase() + value.substring(1);

T? _firstOrNull<T>(Iterable<T> values) {
  for (final value in values) {
    return value;
  }
  return null;
}
